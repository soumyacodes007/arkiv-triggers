// Rebuilds OpenTrigger's on-chain evidence from Arkiv itself, so nobody has to take PROOF.md on trust.
//   npm run evidence            prints the evidence (anonymous reads; set ARKIV_ACCESS_KEY to use a key)
//   npm run evidence -- --write rewrites PROOF.md's generated section
//
// For each of our wallets: transactions sent, receipts written (by status), and its newest receipts with
// links to the receipt, the rule it fired and the transaction that created it. Everything here is read
// with public queries; the queries are printed so they can be pasted into any Arkiv tool.
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { ENTITY_EVENTS_ABI, createPublicClient, str } from "@arkiv-network/sdk"
import { tiramisu } from "@arkiv-network/sdk/chains"
import { and, eq } from "@arkiv-network/sdk/query"
import { type Hex, http } from "viem"
import { pageAll, rpcOptions } from "../src/query"
import { TYPES, parseReceipt, parseRule } from "../src/schema"

for (const f of [".env.local", ".env"]) if (existsSync(f)) process.loadEnvFile(f)
const key = process.env.EVIDENCE_ANON ? undefined : process.env.ARKIV_ACCESS_KEY || undefined
const reader: any = createPublicClient({ chain: tiramisu, transport: http(tiramisu.rpcUrls.default.http[0], rpcOptions(key ? { "X-API-KEY": key } : undefined)) })

const EXPLORER = "https://tiramisu.explorer.arkiv.network"
const ARKIV = "0x4400000000000000000000000000000000000044"
const CREATED = ENTITY_EVENTS_ABI.find((e: any) => e.type === "event" && e.name === "EntityCreated") as any
const WALLETS = [
  { role: "Public worker (Railway)", address: "0xf856952A77F9439a55Ad418f5BB3928f4CE807Db" as Hex },
  { role: "Test runner (live suites)", address: "0x1c92087EC55B3B4114c7647ECADe3ab0b494C9b6" as Hex },
]
const short = (h: string, n = 6) => `${h.slice(0, 2 + n)}…${h.slice(-4)}`
const link = (kind: "entity" | "tx" | "address", h: string, n = 6) => `[${short(h, n)}](${EXPLORER}/${kind}/${h})`

async function createdTx(entityKey: Hex, block: bigint): Promise<Hex | undefined> {
  const logs = await reader.getLogs({ address: ARKIV, event: CREATED, args: { entityKey }, fromBlock: block, toBlock: block }).catch(() => [])
  return logs[0]?.transactionHash
}

const head: bigint = await reader.getBlockNumber()
const lines: string[] = []
const out = (s = "") => lines.push(s)

out(`_Generated by \`npm run evidence\` at block ${head} (${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC). Every number below is read from Arkiv; run it again to check._`)
out()
out("| Wallet | Role | Transactions sent | Receipts on Arkiv now (ok / failed / skipped) |")
out("|---|---|---|---|")
const samples: { wallet: string; rows: string[] }[] = []
for (const w of WALLETS) {
  const nonce = await reader.getTransactionCount({ address: w.address })
  const receipts = await pageAll(reader, (c: any) => c.select({ key: true, creator: true, createdAt: true, attributes: true, payload: true }).where(eq("type", str(TYPES.receipt))).createdBy(w.address), parseReceipt)
  const by = (s: string) => receipts.filter((r) => r.status === s).length
  out(`| ${link("address", w.address)} | ${w.role} | ${nonce} | ${receipts.length} (${by("ok")} / ${by("failed")} / ${by("skipped")}) |`)

  // The newest receipts of each action, so every kind of firing has a checkable example.
  const newest = [...receipts].sort((a, b) => (a.createdAt > b.createdAt ? -1 : 1))
  const picks = ["telegram", "webhook", "extend", "receipt"].flatMap((a) => newest.filter((r) => r.action === a).slice(0, a === "receipt" ? 2 : 1))
  const rows: string[] = []
  for (const r of picks) {
    const tx = await createdTx(r.key, r.createdAt)
    const late = r.firedAt - r.deadline
    const detail = r.status === "failed" ? `failed: ${String(r.result.error ?? "").slice(0, 70)}` : r.result.messageId ? `Telegram message ${r.result.messageId}` : r.result.code ? `HTTP ${r.result.code}` : r.result.newExpiresAt ? `extended to block ${r.result.newExpiresAt}` : r.reason
    rows.push(`| ${r.action} | ${r.status} | ${link("entity", r.key)} | ${link("entity", r.rule)} | ${tx ? link("tx", tx) : "—"} | ${r.deadline} → ${r.firedAt} (${late >= 0n ? `${late} blocks after` : `${-late} early`}) | ${detail} |`)
  }
  samples.push({ wallet: `${w.role} ${short(w.address, 4)}`, rows })
}

const rules = await pageAll(reader, (c: any) => c.select({ key: true, creator: true, owner: true, createdAt: true, expiresAt: true, attributes: true, payload: true }).where(eq("type", str(TYPES.rule))), parseRule)
const creators = new Set(rules.map((r) => r.creator.toLowerCase()))
const workers = await pageAll(reader, (c: any) => c.select({ key: true, creator: true, expiresAt: true }).where(and(eq("type", str(TYPES.heartbeat)))), (e: any) => e)
out()
out(`Live right now: **${rules.length} rules** (\`trg.rule\`) from **${creators.size} different wallets**, and **${new Set(workers.map((w: any) => w.creator.toLowerCase())).size} worker heartbeats** (\`trg.worker\`).`)
for (const s of samples) {
  if (!s.rows.length) continue
  out()
  out(`**Newest receipts written by the ${s.wallet}**`)
  out()
  out("| Action | Status | Receipt | Rule it fired | Created in tx | Deadline → fired at (blocks) | Result |")
  out("|---|---|---|---|---|---|---|")
  for (const r of s.rows) out(r)
}
out()
out("Queries used (the form the SDK sends):")
out()
out("```")
for (const w of WALLETS) out(`type = str('trg.receipt') AND $creator = addr(${w.address})`)
out("type = str('trg.rule')")
out("type = str('trg.worker')")
out("```")

const generated = lines.join("\n")
if (process.argv.includes("--write")) {
  const file = "PROOF.md"
  const doc = readFileSync(file, "utf8")
  const start = "<!-- evidence:start -->"
  const end = "<!-- evidence:end -->"
  if (!doc.includes(start) || !doc.includes(end)) throw new Error(`${file} has no ${start} … ${end} section`)
  writeFileSync(file, doc.slice(0, doc.indexOf(start) + start.length) + "\n" + generated + "\n" + doc.slice(doc.indexOf(end)))
  console.log(`${file} updated at block ${head}`)
} else console.log(generated)
process.exit(0)
